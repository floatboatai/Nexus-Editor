/**
 * Minimal dependency-free i18n for the demo renderer.
 *
 * - Dictionaries are flat, typed key trees (shape enforced by `typeof zh`).
 * - The active language is read from localStorage (`nexus-editor-settings`)
 *   and defaults to Chinese. Changing the language reloads the window so all
 *   command-built UI picks up the new dictionary.
 * - ru / ja / ko / id dictionaries currently mirror English and are replaced
 *   by real translations in a single pass once the key set is frozen.
 */

export const LANGS = ["zh", "en", "ru", "ja", "ko", "id"] as const;
export type Lang = (typeof LANGS)[number];

/** Native display names, shown in the language picker itself. */
export const LANGUAGE_NAMES: Record<Lang, string> = {
  zh: "中文",
  en: "English",
  ru: "Русский",
  ja: "日本語",
  ko: "한국어",
  id: "Bahasa Indonesia",
};

const STORAGE_KEY = "nexus-editor-settings";

function readStoredLang(): Lang {
  try {
    const raw = localStorage.getItem(STORAGE_KEY);
    if (raw) {
      const parsed = JSON.parse(raw) as { language?: unknown };
      if (typeof parsed.language === "string" && (LANGS as readonly string[]).includes(parsed.language)) {
        return parsed.language as Lang;
      }
    }
  } catch {
    /* ignore malformed storage */
  }
  return "zh";
}

let cachedLang: Lang | null = null;

export function getLang(): Lang {
  // Cache: t() is called hundreds of times during command-built UI creation.
  // The language only changes via settings, which reloads the whole window
  // (and re-imports this module), so a module-level cache is safe.
  if (cachedLang === null) cachedLang = readStoredLang();
  return cachedLang;
}

