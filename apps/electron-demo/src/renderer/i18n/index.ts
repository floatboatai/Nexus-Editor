export const DICTS: Record<Lang, UiDict> = {
  zh: zhDict,
  en: enDict,
  ru: ruDict,
  ja: jaDict,
  ko: koDict,
  id: idDict,
};

export function currentDict(): UiDict {
  return DICTS[getLang()];
}

/** Translate a key, interpolating `{name}` placeholders. */
export function t(key: DictKey, vars?: Record<string, string | number>): string {
  let text: string = currentDict()[key] ?? zhDict[key];
  if (vars) {
    for (const [name, value] of Object.entries(vars)) {
      text = text.replaceAll(`{${name}}`, String(value));
    }
  }
  return text;
}
