export interface I18n {
  readonly locale: AppLocale;
  t(key: MessageKey, values?: Readonly<Record<string, string | number>>): string;
  setLocale(locale: unknown): void;
  subscribe(listener: () => void): () => void;
}

export function normalizeLocale(locale: unknown): AppLocale {
  return locale === "zh-CN" ? "zh-CN" : "en";
}

export function createI18n(initialLocale: unknown = "en"): I18n {
  let locale = normalizeLocale(initialLocale);
  const listeners = new Set<() => void>();
  return {
    get locale() {
      return locale;
    },
    t(key, values = {}) {
      const message = (locale === "zh-CN" ? zhCN : en)[key] ?? en[key];
      return message.replace(/\{(\w+)\}/g, (match, name: string) =>
        Object.hasOwn(values, name) ? String(values[name]) : match);
    },
    setLocale(next) {
      const normalized = normalizeLocale(next);
      if (normalized === locale) return;
      locale = normalized;
      for (const listener of listeners) listener();
    },
    subscribe(listener) {
      listeners.add(listener);
      return () => listeners.delete(listener);
    },
  };
}

