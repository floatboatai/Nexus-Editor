const { app, BrowserWindow } = require("electron");
const path = require("node:path");
const fs = require("node:fs");
const checks = [];
const wait = (ms = 100) => new Promise((resolve) => setTimeout(resolve, ms));
const check = (value, message, detail) => { if (!value) throw new Error(message + (detail ? `: ${JSON.stringify(detail)}` : "")); checks.push(message); };
app.whenReady().then(async () => {
  const win = new BrowserWindow({ show: false, width: 900, height: 700, webPreferences: { backgroundThrottling: false, disableHtmlFullscreenWindowResize: true, partition: `selection-toolbar-smoke-${process.pid}` } });
  win.webContents.on("console-message", (_, level, message) => { if (level >= 3) process.stderr.write(message + "\n"); });
  const run = (expression) => win.webContents.executeJavaScript(`window.selectionSmoke.${expression}`, true);
  const input = (event) => win.webContents.sendInputEvent(event);
  const key = async (keyCode, modifiers = []) => {
    input({ type: "keyDown", keyCode, modifiers });
    if (keyCode === "Enter") input({ type: "char", keyCode: "\r", modifiers });
    input({ type: "keyUp", keyCode, modifiers }); await wait();
  };
  const click = async (point, clickCount = 1, modifiers = []) => {
    input({ type: "mouseDown", ...point, button: "left", clickCount, modifiers });
    input({ type: "mouseUp", ...point, button: "left", clickCount, modifiers }); await wait();
  };
  const drag = async (from, to) => {
    const start = await run(`point(${from})`), end = await run(`point(${to})`);
    input({ type: "mouseDown", ...start, button: "left", clickCount: 1 });
    for (let step = 1; step <= 5; step++) {
      input({ type: "mouseMove", x: Math.round(start.x + (end.x - start.x) * step / 5), y: Math.round(start.y + (end.y - start.y) * step / 5), button: "left", modifiers: ["leftButtonDown"] });
      await wait(20);
    }
    check(!(await run("state()")).visible, "hidden during native drag");
    input({ type: "mouseUp", ...end, button: "left", clickCount: 1 }); await wait();
  };
  try {
    await win.loadFile(path.join(__dirname, "selection-toolbar-smoke.html"));
    win.webContents.setZoomFactor(1);
    win.webContents.focus();
    for (const livePreview of [false, true]) {
      await run(`reset(${livePreview})`);
      await drag(6, 11);
      let state = await run("state()");
      check(state.visible && state.selection.anchor === 6 && state.selection.head === 11, `native drag selection (${livePreview ? "preview" : "source"})`, state);
      await click(await run("button()"));
      state = await run("state()");
      check(state.visible && state.text.startsWith("hello `world`") && state.selection.anchor === 7 && state.selection.head === 12, "click keeps formatted text selected");
      await click(await run("button()"));
      state = await run("state()");
      check(state.visible && state.text.startsWith("hello world") && state.selection.anchor === 6 && state.selection.head === 11, "second click removes inline code");
      await key("Escape"); await run("scroll(10)");
      check(!(await run("state()")).visible, "Escape persists across scroll");
      await click(await run("point(8)"), 2);
      check((await run("state()")).visible, "native double click opens toolbar");
      await run("collapse(6)");
      for (let i = 0; i < 5; i++) await key("Right", ["shift"]);
      state = await run("state()"); check(state.visible, "native Shift+Arrow selection", state);
      await key("F10", ["alt"]);
      check((await run("state()")).toolbarFocus, "Alt+F10 enters toolbar");
      await key("Right");
      await key("Space");
      check((await run("state()")).text.startsWith("hello `world`"), "Space activates focused action");
      await key("Escape");
      check((await run("state()")).focus.includes("cm-content"), "Escape restores editor focus");
      await run(`reset(${livePreview})`); await drag(6, 11);
      check((await run("state()")).actions.join(",") === "link,inline-code,text-color", "demo action order is link, inline code, color");
      await click(await run('button("link")'));
      state = await run("state()");
      check(state.visible && state.text.startsWith("hello [world](url)") && state.text.slice(state.selection.anchor, state.selection.head) === "url", "link inserts template and selects destination", state);
      await key("z", [process.platform === "darwin" ? "meta" : "control"]);
      check((await run("state()")).text.startsWith("hello world"), "link insertion is one undo step");
      await run(`reset(${livePreview})`); await drag(6, 11);
      await click(await run('button("text-color")'));
      check((await run("state()")).colorPicker, "color action opens a picker");
      await key("Right"); await key("Right");
      check((await run("state()")).focusedAction === "Red", "arrow keys navigate picker swatches", await run("state()"));
      await key(livePreview ? "Enter" : "Space");
      state = await run("state()");
      check(state.visible && !state.colorPicker && state.text.startsWith('hello <span style="color:#dc2626">world</span>') && state.text.slice(state.selection.anchor, state.selection.head) === "world", "keyboard color choice preserves selected text", state);
      await key("z", [process.platform === "darwin" ? "meta" : "control"]);
      check((await run("state()")).text.startsWith("hello world"), "color application is one undo step");
      await run(`reset(${livePreview})`); await drag(6, 11);
      await click(await run('button("text-color")'));
      await click(await run('target(".nexus-selection-color-picker [aria-label=Blue]")'));
      state = await run("state()");
      check(state.visible && !state.colorPicker && state.text.startsWith('hello <span style="color:#2563eb">world</span>'), "mouse color choice applies to source selection", state);

      await run(`reset(${livePreview})`); await drag(6, 11);
      await click(await run('button("text-color")')); await key("Escape");
      state = await run("state()");
      check(state.visible && !state.colorPicker && state.text.startsWith("hello world"), "Escape cancels color picker without editing");
      await click(await run('button("text-color")')); await click({ x: 800, y: 600 });
      state = await run("state()");
      check(!state.visible && !state.colorPicker && state.text.startsWith("hello world"), "outside click closes picker and selection session");
      await run(`reset(${livePreview})`); await drag(6, 11);
      await click(await run('button("text-color")')); await run('replaceDocument("new document")');
      state = await run("state()");
      check(!state.colorPicker && state.text === "new document", "document change aborts pending color choice");
      await run(`reset(${livePreview})`); await drag(6, 40);
      check((await run("state()")).visible, "selection across paragraphs");
      await run(`reset(${livePreview})`); await drag(11, 6);
      check((await run("state()")).visible, "reversed native selection");
      await click({ x: 800, y: 600 }); check(!(await run("state()")).visible, "outside click dismisses");
    }
    const text = "A long paragraph with enough words to wrap across several visual lines. ".repeat(5) + "\n\n" + "More body text for scrolling.\n\n".repeat(45);
    await run(`reset(true, ${JSON.stringify(text)})`); await run("resize(340)"); await run("wrap()");
    await drag(5, 100); let state = await run("state()");
    check(state.visible && state.rect.x >= 60 && state.rect.x + state.rect.width <= 400, "wrapped selection clamps inside narrow editor", state);
    await click(await run('button("text-color")'));
    await run("scroll(1000)");
    state = await run("state()");
    check(!state.visible && !state.colorPicker, "scroll closes picker and offscreen anchor hides toolbar");
    await run("scroll(0)"); check((await run("state()")).visible, "scrolling anchor back restores session");
    check(await run("fullscreen()"), "fullscreen reparents overlay");
    await run("exitFullscreen()");
    check((await run("state()")).visible, "exiting fullscreen preserves session");
    const light = (await run("state()")).colors.background;
    await run("theme()");
    check((await run("state()")).colors.background !== light, "theme change updates overlay colors");
    win.webContents.debugger.attach("1.3");
    await win.webContents.debugger.sendCommand("Input.imeSetComposition", { text: "文", selectionStart: 1, selectionEnd: 1 });
    await wait();
    check(!(await run("state()")).visible, "native Chromium composition dismisses toolbar");
    await win.webContents.debugger.sendCommand("Input.insertText", { text: "文" });
    win.webContents.debugger.detach();
    await run("reset(true)"); await drag(6, 11);
    win.webContents.setZoomFactor(1.25); await wait();
    check((await run("state()")).visible, "text scaling preserves visible toolbar");
    win.webContents.setZoomFactor(1); await wait();
    await run("reset(true)"); await drag(6, 11);
    await click(await run('target(".nexus-toolbar [data-toolbar-action=inline-code]")'));
    check((await run("state()")).text.startsWith("hello `world`"), "global toolbar still formats selection");
    await run('reset(true, "")');
    input({ type: "char", keyCode: "/bo" }); await wait(300);
    check(await run("slashVisible()"), "slash menu still opens");
    await key("Enter");
    check((await run("state()")).text === "****", "slash menu still executes shared bold command");
    await run("reset(true)");
    await click(await run("point(2)")); await click(await run("point(8)"), 1, ["alt"]);
    state = await run("state()"); check(state.ranges.length === 2 && !state.visible, "native Alt-click keeps multiple cursors and suppresses floating UI");
    const code = "intro\n\n```js\ncode here\n```\n";
    await run(`reset(true, ${JSON.stringify(code)})`); await drag(code.indexOf("code"), code.indexOf("here") + 4);
    check(!(await run("state()")).visible, "code-block selection stays excluded");
    await run(`reset(true, ${JSON.stringify("intro\n\n| A | B |\n| --- | --- |\n| one | two |\n")})`);
    await click(await run('target("td.nexus-cell")'));
    state = await run("state()");
    check(!state.visible && state.focus.includes("nexus-cell"), "table cell editing stays excluded", state);
    input({ type: "char", keyCode: "X" }); await wait(); await click(await run("point(2)")); await wait(200);
    state = await run("state()"); check(state.text.includes("X") && state.text.includes("two"), "table cell editing still commits without disturbing adjacent cells", state);
    await run('reset(false, "hello world", { toolbar: false, selectionToolbar: true })');
    await drag(6, 11);
    state = await run("state()");
    check(!state.globalToolbar && state.visible, "selection toolbar opens without global toolbar");
    await click(await run("button()"));
    check((await run("state()")).text === "hello `world`", "independent selection UI uses shared inline-code action");
    await run('reset(false, "hello world", { toolbar: false, selectionToolbar: false })');
    await drag(6, 11);
    state = await run("state()");
    check(!state.globalToolbar && !state.selectionToolbar, "both toolbar UIs can be disabled");
    await key("b", [process.platform === "darwin" ? "meta" : "control"]);
    check((await run("state()")).text === "hello **world**", "formatting shortcut works with both toolbar UIs disabled");
    await run("reset(true)"); await drag(6, 11);
    fs.writeFileSync(path.join(__dirname, "selection-toolbar.png"), (await win.webContents.capturePage()).toPNG());
    await click(await run('button("text-color")'));
    fs.writeFileSync(path.join(__dirname, "selection-toolbar-color-picker.png"), (await win.webContents.capturePage()).toPNG());
    check(await run("destroy()") === 0 && !(await run("state()")).colorPicker, "destroy removes overlay and pending color picker");
    process.stdout.write(JSON.stringify({ ok: true, checks }) + "\n"); app.exit(0);
  } catch (error) {
    fs.writeFileSync(path.join(__dirname, "selection-toolbar-failure.png"), (await win.webContents.capturePage()).toPNG());
    process.stdout.write(JSON.stringify({ ok: false, checks, error: error.stack }) + "\n"); app.exit(1);
  }
});
setTimeout(() => { process.stderr.write(JSON.stringify({ ok: false, error: "Selection smoke timed out", checks }) + "\n"); app.exit(1); }, 45000);
