import { spawnSync } from "node:child_process";
import { createRequire } from "node:module";
import fs from "node:fs";
import { tmpdir } from "node:os";
import path from "node:path";
import { fileURLToPath } from "node:url";
const scripts = path.dirname(fileURLToPath(import.meta.url));
const appDir = path.dirname(scripts);
const output = fs.mkdtempSync(path.join(tmpdir(), "nexus-selection-toolbar-smoke-"));
process.stdout.write(`Smoke artifacts: ${output}\n`);
const result = spawnSync("pnpm", ["exec", "tsup", path.join(scripts, "selection-toolbar-smoke-renderer.ts"), "--format", "iife", "--platform", "browser", "--out-dir", output, "--no-splitting"], { cwd: appDir, stdio: "inherit" });
if (result.status !== 0) process.exit(result.status ?? 1);
fs.copyFileSync(path.join(scripts, "selection-toolbar-smoke-main.cjs"), path.join(output, "selection-toolbar-smoke-main.cjs"));
fs.writeFileSync(path.join(output, "selection-toolbar-smoke.html"), '<!doctype html><meta charset="utf-8"><script defer src="./selection-toolbar-smoke-renderer.global.js"></script>');
const require = createRequire(import.meta.url);
const env = { ...process.env };
delete env.ELECTRON_RUN_AS_NODE;
const run = spawnSync(require("electron"), [path.join(output, "selection-toolbar-smoke-main.cjs")], { cwd: appDir, stdio: "inherit", env, timeout: 55000 });
process.exit(run.status ?? 1);
